-- OurSecurity initial schema (PostgreSQL). Enum columns are plain text so new values only need a code change.

create table app_user (
    id            bigint generated by default as identity primary key,
    name          varchar(100)  not null,
    phone         varchar(20)   not null unique,
    password_hash varchar(100)  not null,
    role          varchar(20)   not null,
    flat_number   varchar(20),
    active        boolean       not null default true,
    created_at    timestamp(6) with time zone not null
);

create table visit (
    id               bigint generated by default as identity primary key,
    visitor_name     varchar(100) not null,
    visitor_phone    varchar(20),
    purpose          varchar(200),
    flat_number      varchar(20)  not null,
    status           varchar(20)  not null,
    pass_code        varchar(6),
    expected_at      timestamp(6) with time zone,
    valid_until      timestamp(6) with time zone,
    created_at       timestamp(6) with time zone not null,
    checked_in_at    timestamp(6) with time zone,
    checked_out_at   timestamp(6) with time zone,
    created_by_id    bigint not null references app_user (id),
    responded_by_id  bigint references app_user (id),
    checked_in_by_id bigint references app_user (id)
);
create index idx_visit_flat on visit (flat_number);
create index idx_visit_status on visit (status);
create index idx_visit_pass_code on visit (pass_code);
create index idx_visit_checked_in_at on visit (checked_in_at);

create table delivery (
    id           bigint generated by default as identity primary key,
    flat_number  varchar(20)  not null,
    courier      varchar(100) not null,
    description  varchar(300),
    status       varchar(20)  not null,
    instruction  varchar(20),
    received_at  timestamp(6) with time zone not null,
    collected_at timestamp(6) with time zone,
    logged_by_id bigint not null references app_user (id)
);
create index idx_delivery_flat on delivery (flat_number);
create index idx_delivery_status on delivery (status);

create table emergency_alert (
    id                 bigint generated by default as identity primary key,
    type               varchar(20) not null,
    message            varchar(500),
    status             varchar(20) not null,
    raised_by_id       bigint not null references app_user (id),
    flat_number        varchar(20),
    created_at         timestamp(6) with time zone not null,
    acknowledged_by_id bigint references app_user (id),
    acknowledged_at    timestamp(6) with time zone,
    resolved_by_id     bigint references app_user (id),
    resolved_at        timestamp(6) with time zone
);
create index idx_alert_status on emergency_alert (status);
create index idx_alert_raised_by on emergency_alert (raised_by_id);

create table notice (
    id           bigint generated by default as identity primary key,
    title        varchar(200)  not null,
    body         varchar(4000) not null,
    created_at   timestamp(6) with time zone not null,
    posted_by_id bigint not null references app_user (id)
);

create table notification (
    id           bigint generated by default as identity primary key,
    recipient_id bigint not null references app_user (id),
    type         varchar(40)  not null,
    title        varchar(255) not null,
    body         varchar(1000),
    reference_id bigint,
    is_read      boolean not null default false,
    created_at   timestamp(6) with time zone not null
);
create index idx_notification_recipient on notification (recipient_id, created_at);

create table device_token (
    id         bigint generated by default as identity primary key,
    token      varchar(255) not null unique,
    platform   varchar(20)  not null,
    user_id    bigint not null references app_user (id),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null
);
create index idx_device_token_user on device_token (user_id);
